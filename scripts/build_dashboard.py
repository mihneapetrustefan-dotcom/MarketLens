def table_exists(conn: sqlite3.Connection, name: str) -> bool:
    return conn.execute(
        "SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (name,)
    ).fetchone() is not None


def scalar(conn: sqlite3.Connection, sql: str, params: tuple = (), default=None):
    try:
        row = conn.execute(sql, params).fetchone()
        return row[0] if row and row[0] is not None else default
    except sqlite3.OperationalError:
        return default


def rows(conn: sqlite3.Connection, sql: str, params: tuple = ()) -> List[tuple]:
    try:
        return conn.execute(sql, params).fetchall()
    except sqlite3.OperationalError:
        return []


def human_mb(byte_count: float) -> str:
    return f"{byte_count / (1024 * 1024):.1f} MB"


def esc(value: Any) -> str:
    return html.escape(str(value)) if value is not None else ""


def fmt_num(value: Optional[float], digits: int = 0) -> str:
    if value is None:
        return "—"
    return f"{value:,.{digits}f}"


def fmt_pct(value: Optional[float], digits: int = 1) -> str:
    if value is None:
        return "—"
    return f"{value * 100:.{digits}f}%"


def fmt_signed_pct(value: Optional[float], digits: int = 2) -> str:
    if value is None:
        return "—"
    sign = "+" if value >= 0 else ""
    return f"{sign}{value * 100:.{digits}f}%"


