def render_flow_strip(flow: List[Dict]) -> str:
    nodes = []
    for i, stage in enumerate(flow):
        count = stage["count"]
        display = fmt_num(count) if count is not None else "n/a"
        empty = " flow-node--empty" if not count else ""
        nodes.append(f"""<div class="flow-node{empty}">
<div class="flow-count">{display}</div>
<div class="flow-label">{esc(stage['label'])}</div>
<div class="flow-unit">{esc(stage['unit'])}</div>
</div>""")
        if i < len(flow) - 1:
            nodes.append('<div class="flow-line"></div>')
    return "\n".join(nodes)


def render_bar_rows(pairs: List[tuple], value_fmt=fmt_num) -> str:
    if not pairs:
        return '<div class="empty-note">Fara date.</div>'
    max_value = max((p[1] or 0) for p in pairs) or 1
    out = []
    for label, value in pairs:
        pct = 100 * (value or 0) / max_value
        out.append(f"""<div class="bar-row">
<div class="bar-label">{esc(label)}</div>
<div class="bar-track"><div class="bar-fill" style="width:{pct:.1f}%"></div></div>
<div class="bar-value">{value_fmt(value)}</div>
</div>""")
    return "\n".join(out)


