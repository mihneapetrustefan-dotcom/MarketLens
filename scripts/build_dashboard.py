def collect_pipeline_flow(conn: sqlite3.Connection) -> List[Dict]:
    """Row counts for the signature flow strip, in pipeline order."""
    stages = [
        ("Ingestie", "articles", "articole"),
        ("Entitati", "article_entities", "legaturi"),
        ("Evenimente", "events", "rapoarte"),
        ("Fuziune", "canonical_events", "evenimente"),
        ("Impact", "event_studies", "studii"),
        ("Cercetare", "research_observations", "observatii"),
        ("Caracteristici", "research_features", "valori"),
        ("Modele", "trained_models", "modele"),
        ("Semnale", "signals", "semnale"),
    ]
    flow = []
    for label, table, unit in stages:
        count = scalar(conn, f"SELECT COUNT(*) FROM {table}") if table_exists(conn, table) else None
        flow.append({"label": label, "count": count, "unit": unit})
    return flow


def collect_health(conn: sqlite3.Connection, db_path: str) -> Dict:
    size = os.path.getsize(db_path) if os.path.exists(db_path) else 0
    total_articles = scalar(conn, "SELECT COUNT(*) FROM articles", default=0) if table_exists(conn, "articles") else 0
    linked_articles = scalar(
        conn, "SELECT COUNT(DISTINCT article_id) FROM article_entities", default=0
    ) if table_exists(conn, "article_entities") else 0
    sources = scalar(conn, "SELECT COUNT(DISTINCT source) FROM articles WHERE source IS NOT NULL", default=0) \
        if table_exists(conn, "articles") else 0
    latest_article = scalar(conn, "SELECT MAX(published_at) FROM articles") if table_exists(conn, "articles") else None
    companies = scalar(conn, "SELECT COUNT(*) FROM companies", default=0) if table_exists(conn, "companies") else 0
    instruments = scalar(conn, "SELECT COUNT(*) FROM instruments", default=0) if table_exists(conn, "instruments") else 0
    return {
        "size_mb": human_mb(size), "total_articles": total_articles,
        "linked_articles": linked_articles,
        "entity_coverage": (linked_articles / total_articles) if total_articles else None,
        "sources": sources, "latest_article": latest_article,
        "companies": companies, "instruments": instruments,
    }


def collect_events(conn: sqlite3.Connection) -> Dict:
    if not table_exists(conn, "canonical_events"):
        return {"available": False}
    total = scalar(conn, "SELECT COUNT(*) FROM canonical_events", default=0)
    corroboration = rows(conn, """
        SELECT corroboration_state, COUNT(*) FROM canonical_events
        GROUP BY corroboration_state ORDER BY 2 DESC""")
    by_type = rows(conn, """
        SELECT event_type, COUNT(*) FROM canonical_events
        GROUP BY event_type ORDER BY 2 DESC LIMIT 8""")
    top_instruments = rows(conn, """
        SELECT cep.entity_id, COUNT(*) c FROM canonical_event_participants cep
        WHERE cep.role='primary' GROUP BY cep.entity_id ORDER BY c DESC LIMIT 8
    """) if table_exists(conn, "canonical_event_participants") else []
    return {"available": True, "total": total, "corroboration": corroboration,
            "by_type": by_type, "top_instruments": top_instruments}


def collect_impact(conn: sqlite3.Connection) -> Dict:
    if not table_exists(conn, "event_studies"):
        return {"available": False}
    total = scalar(conn, "SELECT COUNT(*) FROM event_studies", default=0)
    quality = rows(conn, "SELECT quality_level, COUNT(*) FROM event_studies GROUP BY quality_level ORDER BY 2 DESC")
    by_window = rows(conn, """
        SELECT window_name, COUNT(*), AVG(abnormal_return) FROM event_study_returns
        WHERE abnormal_return IS NOT NULL GROUP BY window_name ORDER BY window_name
    """) if table_exists(conn, "event_study_returns") else []
    return {"available": True, "total": total, "quality": quality, "by_window": by_window}


def collect_research(conn: sqlite3.Connection) -> Dict:
    if not table_exists(conn, "research_observations"):
        return {"available": False}
    total = scalar(conn, "SELECT COUNT(*) FROM research_observations", default=0)
    quality = rows(conn, "SELECT quality_level, COUNT(*) FROM research_observations GROUP BY quality_level ORDER BY 2 DESC")
    feature_coverage = rows(conn, """
        SELECT qualified_name, COUNT(DISTINCT observation_id) FROM research_features
        WHERE source='phase8_feature_engine' AND value_json != 'null'
        GROUP BY qualified_name ORDER BY 2 DESC
    """) if table_exists(conn, "research_features") else []
    total_features_attempted = scalar(conn, """
        SELECT COUNT(DISTINCT qualified_name) FROM research_features WHERE source='phase8_feature_engine'
    """, default=0) if table_exists(conn, "research_features") else 0
    return {"available": True, "total": total, "quality": quality,
            "feature_coverage": feature_coverage, "feature_count": total_features_attempted}


def collect_models(conn: sqlite3.Connection) -> Dict:
    if not table_exists(conn, "trained_models"):
        return {"available": False}
    models = rows(conn, """
        SELECT m.model_qualified_id, m.label_name, m.train_sample_size, m.train_cluster_count,
               e.small_sample, e.beats_all_baselines, e.metrics_json
        FROM trained_models m LEFT JOIN model_evaluations e ON e.trained_model_id = m.trained_model_id
        ORDER BY m.trained_at DESC LIMIT 10
    """) if table_exists(conn, "trained_models") else []
    predictions = scalar(conn, "SELECT COUNT(*) FROM predictions", default=0) if table_exists(conn, "predictions") else 0
    return {"available": True, "models": models, "predictions": predictions}


def collect_signals(conn: sqlite3.Connection) -> Dict:
    if not table_exists(conn, "signals"):
        return {"available": False}
    total = scalar(conn, "SELECT COUNT(*) FROM signals", default=0)
    by_status = rows(conn, "SELECT status, COUNT(*) FROM signals GROUP BY status ORDER BY 2 DESC")
    by_direction = rows(conn, """
        SELECT direction, COUNT(*) FROM signals WHERE status='active' GROUP BY direction ORDER BY 2 DESC
    """)
    suppression = rows(conn, """
        SELECT reason, COUNT(*) FROM signal_suppressions GROUP BY reason ORDER BY 2 DESC
    """) if table_exists(conn, "signal_suppressions") else []
    recent = rows(conn, """
        SELECT instrument_id, direction, status, strength, confidence,
               expected_return, source_information_cutoff
        FROM signals ORDER BY source_information_cutoff DESC LIMIT 12
    """)
    evaluations = rows(conn, """
        SELECT cohort_kind, cohort_value, horizon, sample_size, hit_rate,
               baseline_hit_rate, beats_baseline, small_sample
        FROM signal_evaluations WHERE cohort_kind='overall' ORDER BY horizon
    """) if table_exists(conn, "signal_evaluations") else []
    return {"available": True, "total": total, "by_status": by_status,
            "by_direction": by_direction, "suppression": suppression,
            "recent": recent, "evaluations": evaluations}


def collect_legacy_portfolio(conn: sqlite3.Connection) -> Dict:
    if not table_exists(conn, "recommendations"):
        return {"available": False}
    total_recs = scalar(conn, "SELECT COUNT(*) FROM recommendations", default=0)
    by_rec = rows(conn, "SELECT recommendation, COUNT(*) FROM recommendations GROUP BY recommendation ORDER BY 2 DESC")
    checked = scalar(conn, "SELECT COUNT(*) FROM recommendations WHERE was_correct IS NOT NULL", default=0)
    correct = scalar(conn, "SELECT COUNT(*) FROM recommendations WHERE was_correct = 1", default=0)
    latest_snapshot = rows(conn, """
        SELECT recorded_at, total_invested, total_final_value, total_return_pct, trades_simulated
        FROM portfolio_snapshots ORDER BY recorded_at DESC LIMIT 1
    """) if table_exists(conn, "portfolio_snapshots") else []
    return {"available": True, "total_recs": total_recs, "by_rec": by_rec,
            "checked": checked, "correct": correct,
            "accuracy": (correct / checked) if checked else None,
            "latest_snapshot": latest_snapshot[0] if latest_snapshot else None}


