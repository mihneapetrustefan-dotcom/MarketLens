"""
Builds a comprehensive system dashboard covering every phase of the
pipeline — not just the legacy recommendation/portfolio view that
run_daily.py's DashboardGenerator produces today.

WHY THIS EXISTS AS A SEPARATE SCRIPT
-----------------------------------------
docs/index.html is generated by DashboardGenerator, fed exclusively by
legacy pipeline objects (recommendations, sector_scores, portfolio
history). None of Phases 3–10 — entity resolution, events, fusion,
market impact, research observations, features, models, or signals —
reach it. This script queries all of it: the legacy tables AND every
phase's tables, tolerating any that are missing or empty (an older
export, or a phase not yet run) rather than crashing.

THIS IS A STANDALONE, MANUALLY-TRIGGERED REPLACEMENT
----------------------------------------------------------
It writes to the same path (docs/index.html) but runs as its own
workflow, not wired into the daily pipeline. That is deliberate: the
person asked for this "at least temporarily", and the existing
DashboardGenerator would silently overwrite it on the next automatic
run otherwise. Making that permanent — replacing the daily pipeline's
own report step — is a separate decision.

EVERY SECTION DEGRADES INDEPENDENTLY
-----------------------------------------
Each phase's section is wrapped so a missing table or empty result
renders an honest "no data yet" card instead of taking down the whole
page. A dashboard that goes blank because one late phase has no rows
yet would be worse than one that plainly says so section by section.

NO INVENTED NUMBERS
------------------------
Every figure comes from a query against real tables. Where a metric
cannot be computed (e.g. no baseline, no signals yet), the card says
so rather than showing a zero that could be mistaken for a real
measurement.
"""

